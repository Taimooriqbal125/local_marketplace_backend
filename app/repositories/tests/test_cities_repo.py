def test_create_city(repo: CityRepository):
    """Test creating a new city."""
    city_in = CityCreate(
        name="Karachi",
        country="Pakistan",
        center_point="24.8607,67.0011",
        is_active=True
    )
    city = repo.create(city_in)

    assert city.id is not None
    assert city.name == "Karachi"
    assert city.country == "Pakistan"
    assert city.centerPoint == "24.8607,67.0011"
    assert city.isActive is True
    assert city.slug == "karachi"  # Auto-generated by schema


def test_get_city(repo: CityRepository):
    """Test fetching a city by ID."""
    city_in = CityCreate(name="Lahore", country="Pakistan")
    created = repo.create(city_in)

    fetched = repo.get(created.id)
    assert fetched is not None
    assert fetched.id == created.id
    assert fetched.name == "Lahore"


