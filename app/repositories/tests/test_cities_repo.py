def test_get_all(repo: CityRepository):
    """Test fetching a paginated list of cities."""
    # Create 3 cities
    for i in range(3):
        repo.create(CityCreate(name=f"City {i}", country="Test Country"))

    all_cities = repo.get_all(skip=0, limit=10)
    assert len(all_cities) == 3

    paginated = repo.get_all(skip=1, limit=1)
    assert len(paginated) == 1
    assert paginated[0].name == "City 1"


def test_update_city(repo: CityRepository):
    """Test updating an existing city."""
    created = repo.create(CityCreate(name="Old City", country="Old Country"))
    
    update_in = CityUpdate(name="New City", is_active=False)
    updated = repo.update(created, update_in)

    assert updated.name == "New City"
    assert updated.isActive is False
    assert updated.country == "Old Country"


def test_delete_city(repo: CityRepository):
    """Test deleting a city."""
    created = repo.create(CityCreate(name="To Delete", country="DeleteLand"))
    city_id = created.id

    repo.delete(created)
    
    fetched = repo.get(city_id)
    assert fetched is None
